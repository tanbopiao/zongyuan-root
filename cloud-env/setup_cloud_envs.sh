cat > "$ENV2/assets/character_templates.md" << 'EOF'
# 角色设定模板
## 女娲（创世神女）
- 外观：蛇尾人身，五彩石环绕，洪荒创世氛围
- 服饰：上古兽皮+五彩石配饰
- 常用场景：开天辟地、补天造人、洪荒战场

## 九天玄女（战争形态）
- 外观：红裙凤冠，金甲战甲，手持神兵
- 服饰：烈焰红裙+凤冠+玄铁战甲
- 常用场景：降魔战场、天兵点将、烈焰苍穹

## 九天玄女（道法形态）
- 外观：白衣素裙，手持拂尘，仙山云海
- 服饰：月白道袍+玉簪+拂尘
- 常用场景：道法自然、仙山论道、云海传道

## 真武大帝（降魔形态）
- 外观：玄帝战甲，龟蛇二将随行，北极玄天
- 服饰：玄黑帝袍+真武印+龟蛇护法
- 常用场景：降魔伏妖、北极玄天、武当金顶
EOF

echo "  ✅ 短剧生产环境配置完成"

# ==================== 环境3：元秩序归档 ====================
ENV3="$BASE/meta_archive"
echo ""
echo "[3/3] 配置元秩序归档环境 -> $ENV3"
mkdir -p "$ENV3"/{pending,locked,ledger,scripts,reports}

cat > "$ENV3/README.md" << 'EOF'
# 元秩序归档环境
## 用途
全域资产锁档：哈希确权→台账登记→Merkle-DAG上链→多端归档→链校验。
## 目录
- pending/  待归档资产
- locked/   已锁档资产（只读）
- ledger/   全局账本、哈希链
- scripts/  归档脚本
- reports/  锁档回执
## 锁档等级
Lv1-Lv8，默认Lv8（硬件级永久自治锁档）
## 九大元类
M1理论 / M2算法 / M3工程 / M4文档 / M5数据 / M6多媒体 / M7决策 / M8协议 / M9台账
## 确权
DID-BR-000002 / Ω₀⊂⊙∞⊂Ω
## 常用命令
