## 目录
- episodes/    分集剧本（EP001.md, EP002.md...）
- storyboards/ 分镜表（按集编号）
- keyframes/   关键帧提示词集
- voiceover/   配音台词脚本
- assets/      角色设定、视觉参考、音乐素材
- archive/     已归档剧集
## 技术规范
- 9:16竖屏 / 8K / UE5.7全局光追
- 单段10秒，多段拼接
- 国风仙侠写实厚涂 / 黑金暗纹
- 确权符号：Ω₀⊂⊙∞⊂Ω
## 角色库
女娲 / 九天玄女(战争/道法) / 真武大帝 / KLXN
EOF

