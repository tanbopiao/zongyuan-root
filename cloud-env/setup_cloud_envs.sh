#!/bin/bash
# ============================================================
# 云电脑三环境一键配置脚本
# 环境：灵境研发 / 短剧生产 / 元秩序归档
# 用法：bash setup_cloud_envs.sh
# ============================================================

set -e

echo "============================================"
echo "  云电脑三环境配置启动"
echo "  DID: DID-BR-000002"
echo "  确权: Ω₀⊂⊙∞⊂Ω"
echo "============================================"

# 基础目录
BASE="$HOME/lingjing_cloud"
mkdir -p "$BASE"

# ==================== 环境1：灵境研发 ====================
ENV1="$BASE/lingjing_dev"
echo ""
echo "[1/3] 配置灵境研发环境 -> $ENV1"
mkdir -p "$ENV1"/{src,docs,tests,data,venv}

# 写入环境说明
cat > "$ENV1/README.md" << 'EOF'
# 灵境研发环境
## 用途
六层人机协同可信仿真系统研发、性能迭代、论文撰写。
## 目录
- src/    源码（事件总线、Merkle树、仿真层等）
- docs/   设计文档、论文、架构图
- tests/  测试用例
- data/   仿真数据、快照
- venv/   Python虚拟环境
## 技术栈
Python 3.10+ / pycryptodome / rocksdb(可选)
## 常用命令
python src/lingjing_v4.py
python tests/test_v4.py
EOF

# 初始化git
cd "$ENV1" && git init -q 2>/dev/null || true
echo "  ✅ 灵境研发环境配置完成"

# ==================== 环境2：短剧生产 ====================
ENV2="$BASE/kunlun_drama"
echo ""
echo "[2/3] 配置短剧生产环境 -> $ENV2"
mkdir -p "$ENV2"/{episodes,storyboards,keyframes,voiceover,assets,archive}

cat > "$ENV2/README.md" << 'EOF'
# 昆仑洞天短剧生产环境
## 用途
